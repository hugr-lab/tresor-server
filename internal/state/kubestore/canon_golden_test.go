// the canonical bytes every MAC on a Kubernetes store is over: fixed here, since the MACs at rest depend on them
// (the encoder moved to package canon in spec 014; these vectors were taken from the code before the move)
func TestCanonicalGolden(t *testing.T) {
	sec := secretSpec{Name: "lake", RowID: "r1", Type: "s3", Provider: "config", Scope: []string{"s3://lake"}, Owner: "o",
		Version: 3, CreatedAt: 10, UpdatedAt: 20, Grants: []secretGrant{{ID: "g1", Principal: "role:a", Verbs: []string{"use"}}},
		DataKeyID: "dk", Sealed: []byte{1, 2, 3}}
	g := grantSpec{IDHash: []byte("h"), ActorOwner: "a", ActorClient: "c", ActorIssuer: "i", UserOwner: "u", User: "{}",
		ExpiresAt: 5, SubjectExpiresAt: 6, DataKeyID: "dk"}
	tk := tokenSpec{IDHash: []byte("h"), Key: []byte("api\x00"), Version: 2, Failed: "f", DataKeyID: "dk", Sealed: []byte{9}}
	a := actorSpec{ActorOwner: "a", Counter: 4, DataKeyID: "dk"}
	k := keyringSpec{DataKeyID: "dk", Instance: "inst"}
	for name, got := range map[string][]byte{
		"secret": sec.canonical(kindSecret, "inst"), "grant": g.canonical("inst"), "token": tk.canonical("inst"),
		"actor": a.canonical("inst"), "keyring": k.canonical("inst"),
	} {
		if want := golden[name]; hex.EncodeToString(got) != want {
			t.Errorf("%s: the canonical bytes changed - every MAC at rest would stop verifying", name)
		}
	}
}

